"""The files workbench endpoints (topic 26, area ``files``).

Every endpoint of the demo router, over the per-test app (a fresh store
per test — no state leaks): the panel's real policy constants, the upload
round-trip with its sniff verdict and BOTH names, the 422 rejections
(over-cap, MIME disagreement, undecodable image), the stored inventory,
the download's Content-Disposition in both modes including a non-ASCII
name, the range round-trip (header form and query form → 206 + exact
slice; invalid and unsatisfiable → the 422 envelope), the Pillow round
over an in-test-generated PNG, the traversal verdict, and the paced
stream's chunk sequence with paceMs=0 for speed.
"""

import base64
import io
import json
import re

from fastapi.testclient import TestClient
from PIL import Image

PANEL_PATH = "/api/demo/files"
UPLOAD_PATH = "/api/demo/files/upload"
STORED_PATH = "/api/demo/files/stored"
IMAGES_PATH = "/api/demo/files/images"
TRAVERSAL_PATH = "/api/demo/files/traversal"
STREAM_PATH = "/api/demo/files/stream"

ENVELOPE_CODE = "error"
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def a_png(
    width: int = 320, height: int = 180, color: tuple[int, int, int] = (30, 90, 200)
) -> bytes:
    """A known image, generated by Pillow itself — the deterministic fixture."""
    buffer = io.BytesIO()
    Image.new("RGB", (width, height), color).save(buffer, format="PNG")
    return buffer.getvalue()


def upload(client: TestClient, name: str, body: bytes, content_type: str) -> dict:
    """One multipart upload, returning the parsed outcome row."""
    response = client.post(
        UPLOAD_PATH, files={"file": (name, body, content_type)}
    )
    assert response.status_code == 200, response.text
    return response.json()


def download_path(file_id: str) -> str:
    return f"{PANEL_PATH}/{file_id}/download"


def test_panel_serves_the_real_policy_and_tour(client: TestClient) -> None:
    body = client.get(PANEL_PATH).json()
    assert body["policy"] == {
        "maxUploadBytes": 2 * 1024 * 1024,
        "readChunkBytes": 65536,
        "spoolThresholdBytes": 1024 * 1024,
        "thumbnailMaxEdge": 96,
    }
    assert len(body["endpoints"]) == 7
    assert any("SIMULATED" in note or "simulated" in note for note in body["honestyNotes"])
    assert body["storedFiles"] == []


def test_upload_round_trip_records_metadata_and_sniff(client: TestClient) -> None:
    outcome = upload(client, "拍chapter.txt", b"chapter bytes", "text/plain")
    assert outcome["file"]["displayName"] == "拍chapter.txt"
    assert outcome["file"]["sanitizedName"] == "chapter.txt"
    assert outcome["file"]["sniffedType"] == "text/plain"
    assert outcome["file"]["sizeBytes"] == 13
    assert re.fullmatch(r"f-[0-9a-f]{8}", outcome["file"]["fileId"])
    assert outcome["sniff"]["agrees"] is True

    stored = client.get(STORED_PATH).json()
    assert stored["count"] == 1
    assert stored["files"][0]["fileId"] == outcome["file"]["fileId"]


def test_oversized_upload_is_the_422_envelope(client: TestClient) -> None:
    response = client.post(
        UPLOAD_PATH,
        files={"file": ("big.bin", b"x" * (2 * 1024 * 1024 + 1), "application/octet-stream")},
    )
    assert response.status_code == 422
    error = response.json()[ENVELOPE_CODE]
    assert error["code"] == "validation_failed"
    assert error["details"]["maxUploadBytes"] == 2 * 1024 * 1024
    # Nothing was stored — the rejection left no residue.
    assert client.get(STORED_PATH).json()["count"] == 0


def test_mime_disagreement_is_the_422_envelope(client: TestClient) -> None:
    response = client.post(
        UPLOAD_PATH, files={"file": ("fake.jpg", a_png(), "image/jpeg")}
    )
    assert response.status_code == 422
    error = response.json()[ENVELOPE_CODE]
    assert error["details"]["sniffedType"] == "image/png"
    assert error["details"]["declaredType"] == "image/jpeg"


def test_download_serves_disposition_in_both_modes(client: TestClient) -> None:
    file_id = upload(client, "notes.txt", b"hello world", "text/plain")["file"]["fileId"]

    attached = client.get(download_path(file_id))
    assert attached.status_code == 200
    assert attached.content == b"hello world"
    assert attached.headers["content-type"].startswith("text/plain")
    assert attached.headers["content-disposition"] == 'attachment; filename="notes.txt"'
    assert attached.headers["accept-ranges"] == "bytes"

    inline = client.get(f"{download_path(file_id)}?mode=inline")
    assert inline.headers["content-disposition"] == 'inline; filename="notes.txt"'


def test_download_encodes_non_ascii_names_per_rfc_5987(client: TestClient) -> None:
    file_id = upload(client, "拍data.txt", b"payload", "text/plain")["file"]["fileId"]
    disposition = client.get(download_path(file_id)).headers["content-disposition"]
    assert disposition == (
        'attachment; filename="data.txt"; filename*=UTF-8\'\'%E6%8B%8Ddata.txt'
    )


def test_unknown_download_is_the_404_envelope(client: TestClient) -> None:
    response = client.get(download_path("f-0000ffff"))
    assert response.status_code == 404
    assert response.json()[ENVELOPE_CODE]["code"] == "not_found"


def test_range_round_trip_header_and_query_forms(client: TestClient) -> None:
    file_id = upload(client, "chapter.txt", b"hello world", "text/plain")["file"]["fileId"]

    by_header = client.get(download_path(file_id), headers={"Range": "bytes=0-4"})
    assert by_header.status_code == 206
    assert by_header.content == b"hello"
    assert by_header.headers["content-range"] == "bytes 0-4/11"

    by_query = client.get(f"{download_path(file_id)}?bytes=6-10")
    assert by_query.status_code == 206
    assert by_query.content == b"world"
    assert by_query.headers["content-range"] == "bytes 6-10/11"

    suffix = client.get(download_path(file_id), headers={"Range": "bytes=-5"})
    assert suffix.status_code == 206 and suffix.content == b"world"


def test_invalid_and_unsatisfiable_ranges_answer_the_422_envelope(
    client: TestClient,
) -> None:
    file_id = upload(client, "chapter.txt", b"hello world", "text/plain")["file"]["fileId"]

    garbage = client.get(download_path(file_id), headers={"Range": "bytes=a-b"})
    assert garbage.status_code == 422
    assert garbage.json()[ENVELOPE_CODE]["code"] == "validation_failed"

    past_eof = client.get(download_path(file_id), headers={"Range": "bytes=99-"})
    assert past_eof.status_code == 422
    assert past_eof.json()[ENVELOPE_CODE]["details"]["fileSizeBytes"] == 11


def test_image_round_derives_variants_from_the_pixels(client: TestClient) -> None:
    response = client.post(
        IMAGES_PATH, files={"file": ("sky.png", a_png(), "image/png")}
    )
    assert response.status_code == 200, response.text
    body = response.json()
    assert (body["width"], body["height"], body["decodedFormat"]) == (320, 180, "PNG")

    thumbnail = Image.open(io.BytesIO(base64.b64decode(body["thumbnailDataUrl"].split(",", 1)[1])))
    assert thumbnail.size == (96, 54) and thumbnail.format == "PNG"
    grayscale = Image.open(io.BytesIO(base64.b64decode(body["grayscaleDataUrl"].split(",", 1)[1])))
    assert grayscale.size == (320, 180) and grayscale.mode == "L"
    # The upload was stored through the same pipeline everything else uses.
    assert client.get(STORED_PATH).json()["count"] == 1


def test_truncated_image_is_a_clean_422_not_a_500(client: TestClient) -> None:
    whole = a_png()
    response = client.post(
        IMAGES_PATH, files={"file": ("trunc.png", whole[: len(whole) // 2], "image/png")}
    )
    assert response.status_code == 422
    assert response.json()[ENVELOPE_CODE]["code"] == "validation_failed"


def test_traversal_endpoint_shows_the_defense(client: TestClient) -> None:
    response = client.post(TRAVERSAL_PATH, json={"name": "../../etc/passwd"})
    assert response.status_code == 200
    body = response.json()
    assert body["sanitizedName"] == "etcpasswd"
    assert body["accepted"] is False
    assert body["containmentHolds"] is False
    assert "server-minted" in body["storageKey"]

    benign = client.post(TRAVERSAL_PATH, json={"name": "photo.png"}).json()
    assert benign["accepted"] is True


def test_traversal_named_upload_is_sanitized_not_stored_as_sent(client: TestClient) -> None:
    outcome = upload(
        client, "../../etc/passwd", b"not the password file", "text/plain"
    )
    assert outcome["file"]["sanitizedName"] == "etcpasswd"
    assert outcome["file"]["displayName"] == "../../etc/passwd"
    # The stored id is minted entropy; the download path serves it safely.
    assert client.get(download_path(outcome["file"]["fileId"])).status_code == 200


def test_stream_yields_the_planned_chunk_sequence(client: TestClient) -> None:
    response = client.get(f"{STREAM_PATH}?chunks=3&chunkBytes=64&paceMs=0")
    assert response.status_code == 200
    assert response.headers["x-chunk-count"] == "3"
    assert response.headers["x-chunk-bytes"] == "64"
    assert response.headers["content-type"].startswith("application/x-ndjson")

    lines = response.text.splitlines()
    assert len(lines) == 3
    chunks = [json.loads(line) for line in lines]
    assert [c["chunk"] for c in chunks] == [1, 2, 3]
    assert all(c["of"] == 3 and c["bytes"] == 64 for c in chunks)
    # Each wire line is payload padded to exactly chunkBytes, plus its newline.
    assert all(len(line.encode()) == 64 for line in lines)
    assert len(response.content) == 3 * 65


def test_stream_bounds_are_enforced_by_the_query_contract(client: TestClient) -> None:
    assert client.get(f"{STREAM_PATH}?chunks=65").status_code == 422
    assert client.get(f"{STREAM_PATH}?chunkBytes=4097").status_code == 422
    assert client.get(f"{STREAM_PATH}?paceMs=1001").status_code == 422
