# ── the service: streamed cap, sniff gate, ranges, traversal ───────────────────


def make_reader(payload: bytes, chunk_size: int = 7):
    """An UploadFile.read-shaped async reader over an in-memory payload."""

    async def read(size: int) -> bytes:
        nonlocal payload
        take = payload[: min(size, chunk_size, len(payload))]
        payload = payload[len(take) :]
        return take

    return read


def fresh_service() -> FilesWorkbenchService:
    counter = iter(range(1, 100))

    def next_id() -> str:
        return f"f-{next(counter):08d}"

    return FilesWorkbenchService(
        InMemoryFileStore(id_factory=next_id, clock=lambda: FIXED_CLOCK_NOW)
    )


async def test_upload_round_trip_records_both_names_and_sniff() -> None:
    service = fresh_service()
    outcome = await service.upload("拍data.txt", "text/plain", make_reader(b"hello"))
    assert outcome.record.file_id == "f-00000001"
    assert outcome.record.display_name == "拍data.txt"
    assert outcome.record.sanitized_name == "data.txt"
    assert outcome.record.size_bytes == 5
    assert outcome.sniff.agrees and outcome.sniff.sniffed_type == "text/plain"


async def test_upload_enforces_the_cap_while_reading() -> None:
    service = fresh_service()
    payload = b"x" * (MAX_UPLOAD_BYTES + 10)
    with pytest.raises(AppError) as raised:
        await service.upload(
            "big.bin", "application/octet-stream", make_reader(payload, chunk_size=65536)
        )
    assert raised.value.kind is FailureKind.VALIDATION_FAILED
    assert raised.value.details["observedBytes"] <= MAX_UPLOAD_BYTES + 65536  # held bounded


async def test_upload_refuses_mime_disagreement_and_nameless_residue() -> None:
    service = fresh_service()
    with pytest.raises(AppError) as mismatch:
        await service.upload("fake.jpg", "image/jpeg", make_reader(PNG_MAGIC + b"x"))
    assert mismatch.value.kind is FailureKind.VALIDATION_FAILED
    with pytest.raises(AppError) as nameless:
        await service.upload("../..", "text/plain", make_reader(b"data"))
    assert nameless.value.details["submittedName"] == "../.."


async def test_ranged_download_serves_windows_and_refuses_the_rest() -> None:
    service = fresh_service()
    outcome = await service.upload("chapter.txt", "text/plain", make_reader(b"hello world"))
    file_id = outcome.record.file_id

    assert service.ranged_download(file_id, None) is None  # no range → full 200 path

    exact = service.ranged_download(file_id, "bytes=0-4")
    assert exact is not None
    _record, body, resolved = exact
    assert body == b"hello" and resolved.content_range == "bytes 0-4/11"

    suffix_body = service.ranged_download(file_id, "bytes=-5")
    assert suffix_body is not None and suffix_body[1] == b"world"

    with pytest.raises(AppError) as invalid:
        service.ranged_download(file_id, "bytes=not-a-range")
    assert "one envelope" in str(invalid.value.details["divergence"])
    with pytest.raises(AppError) as unsatisfiable:
        service.ranged_download(file_id, "bytes=99-")
    assert unsatisfiable.value.details["fileSizeBytes"] == 11


async def test_traversal_verdict_shows_all_three_layers() -> None:
    service = fresh_service()
    escape = service.traversal_verdict("../../etc/passwd")
    assert escape.sanitized_name == "etcpasswd"
    assert not escape.containment_holds and not escape.accepted

    benign = service.traversal_verdict("photo.png")
    assert benign.sanitized_name == "photo.png"
    assert benign.containment_holds and benign.accepted
