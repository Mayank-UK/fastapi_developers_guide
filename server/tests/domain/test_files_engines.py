FIXED_CLOCK_NOW = datetime(2026, 10, 17, 12, 0, 0, tzinfo=UTC)
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
JPEG_MAGIC = b"\xff\xd8\xff\xe0"


def a_png(
    width: int = 320, height: int = 180, color: tuple[int, int, int] = (200, 60, 30)
) -> bytes:
    """A known image, generated by Pillow itself — the deterministic fixture."""
    buffer = io.BytesIO()
    Image.new("RGB", (width, height), color).save(buffer, format="PNG")
    return buffer.getvalue()


