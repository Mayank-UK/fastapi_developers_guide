"""Topic 26's files engines: naming, validation, ranges, disposition, storage, images.

Every engine is pure or injected (id factory, clock), so the whole surface
is deterministic unit tests: the sanitizer's multi-vector table, the range
parser's grammar table and resolution clamps, the disposition builder's
RFC 6266/5987 pair with header injection refused, the store's round-trip,
Pillow's variants over an in-test-generated PNG (determinism pinned), and
the service that composes them — including the streamed cap enforcement.
"""

